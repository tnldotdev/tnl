import * as z from "zod";
import { TnlError } from "../../errors.js";
import { serviceNameSchema, httpsOriginSchema } from "../values.js";
import { publicationRunSchema, publisherURLSchema } from "../publication_run.js";
import { bindEnrollment, type PublisherEnrollment } from "./enrollment.js";

const targetName = z.string().regex(/^[A-Za-z_$][A-Za-z0-9_$]{0,127}$/);
export const workerTarget = z.union([
  z.strictObject({ entrypoint: targetName }),
  z.strictObject({ binding: targetName }),
  z.strictObject({}),
]);
export type WorkerPublicationTarget =
  | { readonly entrypoint: string; readonly binding?: never }
  | { readonly binding: string; readonly entrypoint?: never }
  | { readonly entrypoint?: never; readonly binding?: never };

const resultSchema = z.strictObject({
  id: z.uuid(),
  url: httpsOriginSchema.exactOptional(),
  run: publicationRunSchema.exactOptional(),
  publisherURL: publisherURLSchema.exactOptional(),
});
export type WorkerPublicationData = z.input<typeof resultSchema>;
export type WorkerPublication = Readonly<z.output<typeof resultSchema>> & {
  close(): Promise<void>;
  [Symbol.asyncDispose](): Promise<void>;
};

export interface WorkerPublisherRPC {
  open(controlUrl?: string, enrollment?: () => Promise<string>): Promise<unknown>;
  start(service: string, target: WorkerPublicationTarget): Promise<unknown>;
  stop(service: string, id: string): Promise<void>;
}

export interface WorkerPublisher {
  readonly publisherIdentityID: string;
  readonly deploymentID: string;
}

export interface WorkerPublisherOptions {
  readonly controlUrl?: string;
  readonly instance?: string;
  readonly enrollment?: PublisherEnrollment;
}

const optionsSchema = z.strictObject({
  controlUrl: httpsOriginSchema.exactOptional(),
  instance: serviceNameSchema.exactOptional(),
  enrollment: z
    .union([
      z.string().min(1).max(256),
      z.custom<Exclude<PublisherEnrollment, string>>((value) => typeof value === "function"),
    ])
    .exactOptional(),
});
const ownerSchema = z.strictObject({
  publisherIdentityID: z.string().regex(/^pub_[A-Za-z0-9]{22}$/),
  deploymentID: z.string().regex(/^dpl_[A-Za-z0-9]{22}$/),
});
const owners = new WeakMap<WorkerPublisher, WorkerPublisherRPC>();

export async function publisher(
  ctx: { readonly exports: unknown },
  options: WorkerPublisherOptions = {},
): Promise<WorkerPublisher> {
  const selected = optionsSchema.safeParse(options);
  // ctx.exports is generated by Cloudflare for each Worker. validate only the
  // loopback namespace; do not take a namespace name from a request or secret.
  const bindings = ctx?.exports;
  if (!selected.success || typeof bindings !== "object" || bindings === null)
    throw new TnlError("sdk.configuration_invalid");
  const namespace: unknown = Reflect.get(bindings, "TnlPublisher");
  if ((typeof namespace !== "object" && typeof namespace !== "function") || namespace === null)
    throw new TnlError("sdk.configuration_invalid");
  const getByName: unknown = Reflect.get(namespace, "getByName");
  if (typeof getByName !== "function") throw new TnlError("sdk.configuration_invalid");
  const stub: WorkerPublisherRPC = getByName.call(namespace, selected.data.instance ?? "default");
  const lifetime = new AbortController();
  try {
    const result = await stub.open(
      selected.data.controlUrl,
      selected.data.enrollment === undefined
        ? undefined
        : bindEnrollment(selected.data.enrollment, lifetime.signal),
    );
    const identity = ownerSchema.safeParse(result);
    if (!identity.success) throw new TnlError("sdk.response_invalid");
    const handle = Object.freeze(identity.data);
    owners.set(handle, stub);
    return handle;
  } finally {
    lifetime.abort();
  }
}

export async function publish(
  owner: WorkerPublisher,
  service: string,
  target: WorkerPublicationTarget = {},
): Promise<WorkerPublication> {
  const stub = owners.get(owner);
  const selection = workerTarget.safeParse(target);
  if (stub === undefined || !selection.success || !serviceNameSchema.safeParse(service).success)
    throw new TnlError("sdk.configuration_invalid");
  const evidence = resultSchema.safeParse(await stub.start(service, selection.data));
  if (!evidence.success) throw new TnlError("sdk.response_invalid");
  const close = () => stub.stop(service, evidence.data.id);
  return Object.freeze({ ...evidence.data, close, [Symbol.asyncDispose]: close });
}
