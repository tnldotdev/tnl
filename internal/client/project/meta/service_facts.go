package meta

import (
	"maps"
	"slices"
	"strings"

	"github.com/tnldotdev/tnl/internal/config"
)

// serviceFacts contains application-build facts, never deployment selections,
// private targets, credentials, or browser runtime addresses.
func serviceFacts(configuration config.TNL) []byte {
	var out strings.Builder
	out.WriteString("// generated by tnl generate; do not edit.\nexport const services = Object.freeze({\n")
	for _, name := range slices.Sorted(maps.Keys(configuration.Services)) {
		out.WriteString("  " + typeScriptString(name) + ": Object.freeze({ protocol: " + typeScriptString(config.Protocol(configuration.Services[name])) + " as const }),\n")
	}
	out.WriteString("});\n")
	return []byte(out.String())
}
