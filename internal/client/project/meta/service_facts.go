package meta

import (
	"errors"
	"fmt"
	"slices"
	"strings"

	"github.com/tnldotdev/tnl/internal/config"
	"github.com/tnldotdev/tnl/internal/naming"
)

const ProjectName = "project.ts"

// serviceFacts is one evaluated build snapshot shared by both language outputs.
// selection, targets, identities and permission state never enter this value.
type serviceFacts map[string]string

func snapshotServices(configuration config.TNL) (serviceFacts, error) {
	if len(configuration.Services) > 128 {
		return nil, errors.New("generated project has too many services")
	}
	facts := make(serviceFacts, len(configuration.Services))
	for name, service := range configuration.Services {
		protocol := config.Protocol(service)
		if !naming.ValidServiceName(name) || !config.ValidProtocol(protocol) {
			return nil, errors.New("generated project needs valid service names and protocols")
		}
		facts[name] = protocol
	}
	return facts, nil
}

func (facts serviceFacts) names() []string {
	names := make([]string, 0, len(facts))
	for name := range facts {
		names = append(names, name)
	}
	slices.Sort(names)
	return names
}

// typescriptServices emits data and its literal types together, not an ambient
// declaration or an import of a configuration factory's unevaluated return type.
func typescriptServices(facts serviceFacts) []byte {
	var source strings.Builder
	source.WriteString("// generated by tnl generate; commit this file.\n")
	if len(facts) == 0 {
		source.WriteString("export const services = Object.freeze({});\n")
		return []byte(source.String())
	}
	source.WriteString("export const services = Object.freeze({\n")
	for _, name := range facts.names() {
		key := name
		if strings.Contains(name, "-") {
			key = typeScriptString(name)
		}
		fmt.Fprintf(&source, "  %s: Object.freeze({ protocol: %s }),\n", key, typeScriptString(facts[name]))
	}
	source.WriteString("});\n")
	return []byte(source.String())
}
