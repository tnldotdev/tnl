const PythonDirectoryName = "python"

const pythonGenerated = "# generated by tnl generate; commit this file.\n"

// PythonFacade derives exact overloads only from a static source contract.
// evaluated factory results cannot establish a portable cross-worktree shape.
func PythonFacade(configuration config.TNL, configPath string) (map[string][]byte, error) {
	if configPath == "" {
		return nil, errors.New("project configuration is required for declarations")
	}
	var source strings.Builder
	source.WriteString(pythonGenerated + "from __future__ import annotations\n\nimport os\nfrom typing import Literal, overload\n\nimport tnl as _tnl\n\n")
	static := !strings.EqualFold(filepath.Ext(configPath), ".ts")
	names := make([]string, 0, len(configuration.Services))
	if static {
		for name := range configuration.Services {
			names = append(names, name)
		}
		slices.Sort(names)
	}
	source.WriteString("class _Project:\n")
	protocols := map[string]string{"http": "HTTPConnection", "postgres": "PostgresConnection", "mysql": "MySQLConnection", "tcp": "TCPConnection", "kubernetes": "KubernetesConnection"}
	groups := map[string][]string{}
	for _, name := range names {
		protocol := config.Protocol(configuration.Services[name])
		if protocols[protocol] == "" {
			return nil, errors.New("unsupported service protocol in Python facade")
		}
		groups[protocol] = append(groups[protocol], typeScriptString(name))
	}
	ordered := make([]string, 0, len(groups))
	for protocol := range groups {
		ordered = append(ordered, protocol)
	}
	slices.Sort(ordered)
	for _, protocol := range ordered {
		if len(ordered) > 1 {
			source.WriteString("    @overload\n")
		}
		fmt.Fprintf(&source, "    def connect(self, service: Literal[%s], *, directory: str | os.PathLike[str] | None = None) -> _tnl.%sHandle:", strings.Join(groups[protocol], ", "), protocols[protocol])
		if len(ordered) > 1 {
			source.WriteString(" ...\n\n")
		} else {
			fmt.Fprintf(&source, "\n        return cast(_tnl.%sHandle, _project.connect(service, directory=directory))\n\n", protocols[protocol])
		}
	}
	if len(ordered) != 1 {
		nameType := "str"
		if static && len(names) == 0 {
			nameType = "Never"
		}
		fmt.Fprintf(&source, "    def connect(self, service: %s, *, directory: str | os.PathLike[str] | None = None) -> _tnl.ConnectionHandle[_tnl.Connection]:\n        return _project.connect(service, directory=directory)\n\n", nameType)
	}
	if !static {
		source.WriteString("# generic: a TypeScript factory's evaluated names are not a stable declaration.\n_project = _tnl.Project()\n")
	} else {
		source.WriteString("_project = _tnl.Project({\n")
		for _, name := range names {
			fmt.Fprintf(&source, "    %s: %s,\n", typeScriptString(name), typeScriptString(config.Protocol(configuration.Services[name])))
		}
		source.WriteString("})\n")
	}
	source.WriteString("tnl = _Project()\n")
	if len(ordered) == 0 {
		// these imports are used only by exact static overloads.
		imports := ""
		if static {
			imports = "from typing import Never\n"
		}
		text := strings.ReplaceAll(source.String(), "from typing import Literal, overload\n", imports)
		source.Reset()
		source.WriteString(text)
	} else if len(ordered) == 1 {
		text := strings.ReplaceAll(source.String(), "from typing import Literal, overload", "from typing import Literal, cast")
		source.Reset()
		source.WriteString(text)
	}
	return map[string][]byte{
		"pyproject.toml": []byte(pythonGenerated + `[build-system]
requires = ["hatchling>=1.27,<2"]
build-backend = "hatchling.build"

[project]
name = "tnl-project"
version = "0.0.0"
requires-python = ">=3.12"
dependencies = ["tnldotdev-tnl"]

[tool.hatch.build.targets.wheel]
packages = ["tnl_project"]
`),
		"tnl_project/__init__.py": []byte(source.String()),
		"tnl_project/py.typed":    []byte{},
	}, nil
}

// WritePythonFacade checks or atomically writes this separately owned local
// Python package. every opened directory is pinned and symlinks are rejected.
func WritePythonFacade(directory string, files map[string][]byte, check bool) error {
	absolute, err := filepath.Abs(filepath.Join(directory, PythonDirectoryName))
	if err != nil {
		return err
	}
	root, err := os.OpenRoot(filepath.VolumeName(absolute) + string(filepath.Separator))
	if err != nil {
		return err
	}
	defer func() { root.Close() }()
	for _, part := range strings.Split(strings.TrimPrefix(absolute, filepath.VolumeName(absolute)+string(filepath.Separator)), string(filepath.Separator)) {
		if !check {
			if err := root.Mkdir(part, 0755); err != nil && !errors.Is(err, os.ErrExist) {
				return err
			}
		}
		next, err := pythonChild(root, part)
		if err != nil {
			return err
		}
		root.Close()
		root = next
	}
	if !check {
		if err := root.Mkdir("tnl_project", 0755); err != nil && !errors.Is(err, os.ErrExist) {
			return err
		}
	}
	module, err := pythonChild(root, "tnl_project")
	if err != nil {
		return err
	}
	defer module.Close()
	for name, content := range files {
		parent, base := root, name
		if strings.HasPrefix(name, "tnl_project/") {
			parent, base = module, strings.TrimPrefix(name, "tnl_project/")
		}
		if strings.ContainsAny(base, "/\\") || base == "" || base == "." || base == ".." {
			return errors.New("invalid Python facade artifact path")
		}
		var previous []byte
		info, statErr := parent.Lstat(base)
		if statErr == nil {
			if !info.Mode().IsRegular() || info.Size() > MaxFileBytes {
				return errors.New("python facade artifacts must be bounded regular files")
			}
			file, err := parent.Open(base)
			if err != nil {
				return err
			}
			previous, err = io.ReadAll(io.LimitReader(file, MaxFileBytes+1))
			file.Close()
			if err != nil || len(previous) > MaxFileBytes {
				return errors.New("cannot read Python facade artifact")
			}
		} else if !errors.Is(statErr, os.ErrNotExist) || check {
			return statErr
		}
		if bytes.Equal(previous, content) && statErr == nil {
			continue
		}
		if check {
			return fmt.Errorf("generated Python artifact %s is stale; run tnl generate", name)
		}
		if statErr == nil && !bytes.HasPrefix(previous, []byte(pythonGenerated)) {
			return errors.New("python facade output is not generated; move it before generating")
		}
		temporary := ".tnl-" + rand.Text()
		file, err := parent.OpenFile(temporary, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
		if err != nil {
			return err
		}
		_, writeErr := file.Write(content)
		err = errors.Join(writeErr, file.Sync(), file.Close())
		if err == nil {
			err = parent.Rename(temporary, base)
		}
		_ = parent.Remove(temporary)
		if err != nil {
			return err
		}
	}
	return nil
}

func pythonChild(root *os.Root, name string) (*os.Root, error) {
	info, err := root.Lstat(name)
	if err != nil {
		return nil, err
	}
	if !info.IsDir() {
		return nil, errors.New("python facade directories must not be symlinks")
	}
	child, err := root.OpenRoot(name)
	if err != nil {
		return nil, err
	}
	opened, err := child.Stat(".")
	if err != nil || !os.SameFile(info, opened) {
		child.Close()
		return nil, errors.New("python facade directory changed while opening it")
	}
	return child, nil
}
