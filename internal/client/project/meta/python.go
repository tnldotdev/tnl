package meta

import (
	"errors"
	"fmt"
	"path/filepath"
	"slices"
	"strings"

	"github.com/tnldotdev/tnl/internal/config"
)

const PythonDirectoryName = "python"

const pythonGenerated = "# generated by tnl generate; commit this file.\n"

// PythonFacade writes the service facts used by project-bound clients.
// a TypeScript factory can change service names between worktrees, so callers
// of that form supply the facts when they create a client.
func PythonFacade(configuration config.Project, configPath string) (map[string][]byte, error) {
	if configPath == "" {
		return nil, errors.New("project configuration is required for declarations")
	}
	var source strings.Builder
	source.WriteString(pythonGenerated + "from __future__ import annotations\n\nfrom collections.abc import Awaitable, Callable, Mapping\nfrom typing import Literal, Never, Protocol, cast, overload\n\nimport tnl as _tnl\n\n")
	static := !strings.EqualFold(filepath.Ext(configPath), ".ts")
	names := make([]string, 0, len(configuration.Services))
	if static {
		for name := range configuration.Services {
			names = append(names, name)
		}
		slices.Sort(names)
	}
	source.WriteString("type ServiceProtocol = Literal[\"http\", \"postgres\", \"mysql\", \"tcp\", \"kubernetes\"]\n")
	source.WriteString("type Services = Mapping[str, Mapping[str, ServiceProtocol]]\n\n")
	groups := map[string][]string{}
	if static {
		source.WriteString("services: Services = {\n")
	}
	for _, name := range names {
		protocol := config.DeclaredProtocol(configuration.Services[name])
		if !slices.Contains([]string{"http", "postgres", "mysql", "tcp", "kubernetes"}, protocol) {
			return nil, errors.New("unsupported service protocol in Python facade")
		}
		groups[protocol] = append(groups[protocol], typeScriptString(name))
		fmt.Fprintf(&source, "    %s: {\"protocol\": %s},\n", typeScriptString(name), typeScriptString(protocol))
	}
	if static {
		source.WriteString("}\n\n")
	}
	ordered := make([]string, 0, len(groups))
	for protocol := range groups {
		ordered = append(ordered, protocol)
	}
	slices.Sort(ordered)
	connectionTypes := map[string]string{
		"http": "_tnl.HTTPConnection | _tnl.LocalHTTPConnection", "postgres": "_tnl.PostgresConnection | _tnl.LocalPostgresConnection",
		"mysql": "_tnl.MySQLConnection | _tnl.LocalMySQLConnection", "tcp": "_tnl.TCPConnection | _tnl.LocalTCPConnection", "kubernetes": "_tnl.KubernetesConnection | _tnl.LocalKubernetesConnection",
	}
	source.WriteString("class Deployment(Protocol):\n")
	if len(ordered) == 0 {
		nameType := "str"
		if static {
			nameType = "Never"
		}
		fmt.Fprintf(&source, "    async def connect(self, service: %s) -> _tnl.Connection | _tnl.LocalConnection: ...\n", nameType)
		fmt.Fprintf(&source, "    def client[T](self, service: %s, *, create: Callable[[_tnl.Connection | _tnl.LocalConnection], T | Awaitable[T]], close: Callable[[T], None | Awaitable[None]]) -> _tnl.ClientFactory[T]: ...\n", nameType)
	} else {
		for _, protocol := range ordered {
			if len(ordered) > 1 {
				source.WriteString("    @overload\n")
			}
			fmt.Fprintf(&source, "    async def connect(self, service: Literal[%s]) -> %s: ...\n", strings.Join(groups[protocol], ", "), connectionTypes[protocol])
		}
		for _, protocol := range ordered {
			if len(ordered) > 1 {
				source.WriteString("    @overload\n")
			}
			fmt.Fprintf(&source, "    def client[T](self, service: Literal[%s], *, create: Callable[[%s], T | Awaitable[T]], close: Callable[[T], None | Awaitable[None]]) -> _tnl.ClientFactory[T]: ...\n", strings.Join(groups[protocol], ", "), connectionTypes[protocol])
		}
	}
	source.WriteString("    async def aclose(self) -> None: ...\n\n")
	source.WriteString("def deployment(client: _tnl.Client, name: str) -> Deployment:\n")
	source.WriteString("    return cast(Deployment, client.deployment(name))\n\n")
	if static {
		source.WriteString("def create_client(*, project: str, token: str | None = None) -> _tnl.Client:\n")
		source.WriteString("    return _tnl.create_client(project=project, services=services, token=token)\n")
	} else {
		source.WriteString("def create_client(*, project: str, services: Services, token: str | None = None) -> _tnl.Client:\n")
		source.WriteString("    return _tnl.create_client(project=project, services=services, token=token)\n")
	}
	return map[string][]byte{
		"python/pyproject.toml": []byte(pythonGenerated + `[build-system]
requires = ["hatchling>=1.27,<2"]
build-backend = "hatchling.build"

[project]
name = "tnl-project"
version = "1.0.0"
requires-python = ">=3.12"
dependencies = ["tnldotdev-tnl"]

[tool.hatch.build.targets.wheel]
packages = ["tnl_project"]
`),
		"python/tnl_project/__init__.py": []byte(source.String()),
		"python/tnl_project/py.typed":    []byte{},
	}, nil
}
