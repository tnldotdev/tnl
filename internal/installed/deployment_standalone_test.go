func TestFixedDeploymentListUpgradesPopulatedPrivateRegistry(t *testing.T) {
	options := testOptions(t)
	options.StandaloneDeployments = true
	r, err := Open(t.Context(), options)
	if err != nil {
		t.Fatal(err)
	}
	a, _, ka := kindFixture(t, KindDeployment)
	b, _, kb := kindFixture(t, KindDeployment)
	a.DeploymentMember.DeploymentId = "dpl_0123456789abcdefghijkl"
	b.DeploymentMember.DeploymentId = a.DeploymentMember.DeploymentId
	b.DeploymentInstance = "replica-2"
	// seed the exact encrypted snapshot and signing pins an old fixed-list run left
	// behind. the IDs are fixture constants, not generated by the new registry.
	aOld := restartDefinition(a, "dpl-b01d48349c42bffd6b42f359", 1)
	bOld := restartDefinition(b, "dpl-043fd213b26fc475e2d3a652", 1)
	aOld.Status = Status{State: JobStopped}
	if err := r.retainDeployment(t.Context(), aOld, *aOld.DeploymentMember, ka); err != nil {
		t.Fatal(err)
	}
	if err := r.retainDeployment(t.Context(), bOld, *bOld.DeploymentMember, kb); err != nil {
		t.Fatal(err)
	}
	oldSnapshot, err := json.Marshal([]Job{bOld, aOld})
	if err != nil {
		t.Fatal(err)
	}
	if err := r.database.SavePublisherJobRegistry(t.Context(), oldSnapshot); err != nil {
		t.Fatal(err)
	}
	if err := r.Close(); err != nil {
		t.Fatal(err)
	}
	public := options
	public.StandaloneDeployments = false
	public.User = true
	if rejected, err := OpenExisting(t.Context(), public); !errors.Is(err, ErrLegacyRegistry) {
		if rejected != nil {
			rejected.Close()
		}
		t.Fatal("public registry accepted fixed-list worker IDs", err)
	}
	r, err = Open(t.Context(), options)
	if err != nil {
		t.Fatal("could not open a populated old fixed-list registry", err)
	}
	defer r.Close()
	unchanged, found, err := r.database.PublisherJobRegistry(t.Context())
	if err != nil || !found || !bytes.Equal(unchanged, oldSnapshot) {
		t.Fatal("open rewrote the existing private snapshot", err)
	}
	if _, err := r.ResolveJob(t.Context(), aOld.ID); !errors.Is(err, ErrJobNotFound) {
		t.Fatal("public lookup resolved a private worker ID", err)
	}

	replacement := a
	replacement.PublisherIdentityID, _ = opaqueid.New(opaqueid.PublisherIdentityPrefix)
	wrongMember := *a.DeploymentMember
	wrongMember.PublisherIdentityId = replacement.PublisherIdentityID
	replacement.DeploymentMember = &wrongMember
	if _, err := r.ReplaceDeployments(t.Context(), []DeploymentInstall{{replacement, kb}, {b, kb}}); !errors.Is(err, ErrScope) {
		t.Fatal("different signing identity inherited an old replica", err)
	}
	if _, err := r.ReplaceDeployments(t.Context(), []DeploymentInstall{{a, kb}, {b, kb}}); !errors.Is(err, ErrScope) {
		t.Fatal("another replica's key inherited an old replica", err)
	}
	renamed := *a.DeploymentMember
	renamed.DeploymentName = "renamed"
	a.DeploymentMember = &renamed
	restarted, err := r.ReplaceDeployments(t.Context(), []DeploymentInstall{{a, ka}, {b, kb}})
	if err != nil || restarted[0].ID != aOld.ID || restarted[1].ID != bOld.ID ||
		restarted[0].Revision != 2 || restarted[0].Status.State != JobStarting {
		t.Fatal("upgrade, input order or display rename changed a private worker ID", err)
	}
	for i, expected := range []DeploymentInstall{{a, ka}, {b, kb}} {
		member, private, _, err := r.DeploymentIdentity(t.Context(), restarted[i])
		if err != nil || member != *expected.Job.DeploymentMember || !bytes.Equal(private, expected.Private) {
			t.Fatal("upgrade lost a replica's unchanged signing authority", err)
		}
	}
	moved := a
	moved.DeploymentInstance = "replica-3"
	if _, err := r.ReplaceDeployments(t.Context(), []DeploymentInstall{{moved, ka}}); !errors.Is(err, ErrJobExists) {
		t.Fatal("new replica inherited a different replica's authority", err)
	}
	jobs, err := r.List(t.Context())
	if err != nil || len(jobs) != 2 || !slices.ContainsFunc(jobs, func(j Job) bool { return j.ID == aOld.ID && j.DeploymentInstance == a.DeploymentInstance }) {
		t.Fatal("rejected fixed list changed the existing definition", err)
	}
}

func TestFixedDeploymentRegistryRejectsNonmatchingIDs(t *testing.T) {
	options := testOptions(t)
	options.StandaloneDeployments = true
	r, err := Open(t.Context(), options)
	if err != nil {
		t.Fatal(err)
	}
	defer r.Close()
	job, _, _ := kindFixture(t, KindDeployment)
	wrongReplica := job
	wrongReplica.DeploymentInstance = "replica-2"
	wrongHost := job
	wrongHost.Server = "https://other.example"
	publicID, err := opaqueid.New(opaqueid.JobPrefix)
	if err != nil {
		t.Fatal(err)
	}
	for _, invalidID := range []string{fixedDeploymentID(wrongReplica), fixedDeploymentID(wrongHost), publicID} {
		value, err := json.Marshal([]Job{restartDefinition(job, invalidID, 1)})
		if err != nil {
			t.Fatal(err)
		}
		if err := r.database.SavePublisherJobRegistry(t.Context(), value); err != nil {
			t.Fatal(err)
		}
		if reopened, err := Open(t.Context(), options); !errors.Is(err, ErrUnsafeState) {
			if reopened != nil {
				reopened.Close()
			}
			t.Fatal("accepted an ID for a different binding or registry", err)
		}
	}
}

func TestStandaloneDeploymentsIsolateBlockedStoppedAndHealthyWorkers(t *testing.T) {
	options := testOptions(t)
	options.StandaloneDeployments = true
	r, err := Open(t.Context(), options)
	if err != nil {
		t.Fatal(err)
	}
	defer r.Close()
	a, _, ka := kindFixture(t, KindDeployment)
	b, _, kb := kindFixture(t, KindDeployment)
	b.DeploymentMember.TeamId = "other-team"
	b.Name = a.Name
	installed, err := r.ReplaceDeployments(t.Context(), []DeploymentInstall{{a, ka}, {b, kb}})
	if err != nil {
		t.Fatal(err)
	}
	duplicate := a
	duplicate.DeploymentInstance = "different-instance"
	if _, err := r.InstallDeployment(t.Context(), duplicate, *a.DeploymentMember, ka); !errors.Is(err, ErrScope) {
		t.Fatal("installed deployment crossed into the fixed-list registry", err)
	}
	a = installed[0]
	var healthyStarts, healthyJoins atomic.Int32
	engine := Engine{Registry: r, PollInterval: time.Millisecond, RetryMin: time.Millisecond, RetryMax: 2 * time.Millisecond, Deployment: func(ctx context.Context, job Job, _ *clienttelemetry.Collector, observe func(int64, bool) error, _ func() time.Time, _ context.Context) error {
		if job.ID == a.ID {
			return clientcontrol.ErrUnauthenticated
		}
		healthyStarts.Add(1)
		defer healthyJoins.Add(1)
		if err := observe(1, true); err != nil {
			return err
		}
		<-ctx.Done()
		return nil
	}}
	cancel, done := startEngine(t, engine)
	await(t, func() bool {
		jobs, _ := r.List(t.Context())
		return len(jobs) == 2 && (jobs[0].Status.State == "blocked" && jobs[1].Status.State == "ready" || jobs[1].Status.State == "blocked" && jobs[0].Status.State == "ready")
	})
	if err := r.Stop(t.Context(), a.ID); err != nil {
		t.Fatal(err)
	}
	await(t, func() bool {
		jobs, _ := r.List(t.Context())
		for _, j := range jobs {
			if j.ID == a.ID {
				return j.Status.State == "stopped"
			}
		}
		return false
	})
	if err := r.Start(t.Context(), a.ID); err != nil {
		t.Fatal(err)
	}
	await(t, func() bool {
		jobs, _ := r.List(t.Context())
		for _, j := range jobs {
			if j.ID == a.ID {
				return j.Status.State == "blocked"
			}
		}
		return false
	})
	if healthyStarts.Load() != 1 || healthyJoins.Load() != 0 {
		t.Fatal("A restarted B")
	}
	joinEngine(t, cancel, done)
	if healthyJoins.Load() != 1 {
		t.Fatal("shutdown did not join B")
	}
}
