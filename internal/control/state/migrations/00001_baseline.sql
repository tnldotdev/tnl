        DELETE FROM control.preview_public_urls WHERE preview_id IN (SELECT id FROM control.previews WHERE demo_publish_run_id = NEW.id);
        DELETE FROM control.previews WHERE demo_publish_run_id = NEW.id;
    END IF;
    RETURN NEW;
END;
$$;
