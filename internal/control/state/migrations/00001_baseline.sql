-- a deployment identity can never acquire a namespace or an unrelated exact grant,
-- including through the general publisher-management API.
-- +goose StatementBegin
CREATE FUNCTION control.enforce_deployment_publisher_grant() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.revoked_at IS NULL AND EXISTS (
        SELECT 1 FROM control.deployment_publisher_members member WHERE member.publisher_identity_id=NEW.publisher_identity_id
    ) AND NOT EXISTS (
        SELECT 1 FROM control.deployment_publisher_members member
        JOIN control.deployments deployment ON deployment.id=member.deployment_id AND deployment.deleted_at IS NULL
        JOIN control.applied_project_services service ON service.deployment_id=deployment.id
            AND service.team_id=deployment.team_id AND service.project_key=deployment.project_key
        WHERE member.publisher_identity_id=NEW.publisher_identity_id
           AND NEW.kind='service' AND service.service_id=NEW.service_id
    ) THEN
        RAISE EXCEPTION 'publisher grant is outside its deployment' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd
CREATE TRIGGER enforce_deployment_publisher_grant BEFORE INSERT OR UPDATE ON control.publisher_grants FOR EACH ROW EXECUTE FUNCTION control.enforce_deployment_publisher_grant();

-- exact plan checkpoints outlive certificate-order/run retention and contain no
-- private material. a replica must retain every submitted plan's local keys.
CREATE TABLE control.publisher_certificate_checkpoints (
    publisher_identity_id text NOT NULL REFERENCES control.publisher_identities(id) ON DELETE CASCADE,
    plan_digest text NOT NULL CHECK (plan_digest ~ '^[a-f0-9]{64}$'),
    certificate_plan jsonb NOT NULL CHECK (jsonb_typeof(certificate_plan)='object'),
    PRIMARY KEY (publisher_identity_id,plan_digest)
);

-- +goose StatementBegin
CREATE FUNCTION control.require_publisher_certificate_state() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE publisher text; plan jsonb; digest text;
BEGIN
    SELECT publisher_identity_id INTO publisher FROM control.service_runs WHERE id=NEW.service_run_id;
    IF publisher IS NOT NULL THEN
        -- serialize the per-identity checkpoint capacity check with its owner.
        PERFORM id FROM control.publisher_identities WHERE id=publisher FOR UPDATE;
        plan := jsonb_build_object('cache_key',NEW.certificate_cache_key,'scope',NEW.certificate_scope,
            'identifiers',NEW.certificate_identifiers,'challenge_method',NEW.challenge_method);
        digest := encode(sha256(convert_to(plan::text,'UTF8')),'hex');
        IF NOT EXISTS (SELECT 1 FROM control.publisher_certificate_checkpoints WHERE publisher_identity_id=publisher AND plan_digest=digest) THEN
            IF (SELECT count(*) FROM control.publisher_certificate_checkpoints WHERE publisher_identity_id=publisher)>=1024 THEN
                RAISE EXCEPTION 'publisher certificate checkpoint capacity exceeded' USING ERRCODE='23514';
            END IF;
            INSERT INTO control.publisher_certificate_checkpoints VALUES(publisher,digest,plan);
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd
CREATE TRIGGER require_publisher_certificate_state AFTER INSERT ON control.acme_orders FOR EACH ROW EXECUTE FUNCTION control.require_publisher_certificate_state();

