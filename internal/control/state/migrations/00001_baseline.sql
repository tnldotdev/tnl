CREATE FUNCTION control.active_membership(member_id text, at_time timestamptz)
RETURNS boolean LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM control.team_memberships m
        JOIN control.teams t ON t.id=m.team_id AND t.deleted_at IS NULL
        JOIN control.identities i ON i.id=m.identity_id AND i.disabled_at IS NULL
        WHERE m.id=member_id AND m.removed_at IS NULL AND m.manual_suspended_at IS NULL
        AND (m.personal_account_exception OR
            (NOT t.company_sign_in_required AND m.identity_connection_id IS NULL) OR EXISTS (
                SELECT 1 FROM control.identity_connections c JOIN control.company_eligibility e
                    ON e.identity_connection_id=c.id AND e.team_id=c.team_id
                WHERE c.team_id=t.id AND c.state='active' AND e.identity_id=m.identity_id
                    AND (m.identity_connection_id IS NULL OR m.identity_connection_id=c.id)
                    AND e.connection_revision=c.revision AND e.eligible AND e.valid_until>at_time)))
$$;
-- +goose StatementEnd

-- an explicit identity grant cannot bypass a current or removed company member.
-- +goose StatementBegin
CREATE FUNCTION control.active_team_subject(team text, person text, at_time timestamptz)
RETURNS boolean LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM control.team_memberships m WHERE m.team_id=team AND m.identity_id=person
            AND control.active_membership(m.id, at_time)) OR
        (NOT EXISTS (SELECT 1 FROM control.team_memberships m WHERE m.team_id=team AND m.identity_id=person)
         AND (NOT EXISTS (SELECT 1 FROM control.company_eligibility e JOIN control.identity_connections c ON c.id=e.identity_connection_id WHERE e.team_id=team AND e.identity_id=person AND c.activated_at IS NOT NULL)
          OR EXISTS (SELECT 1 FROM control.identity_connections c JOIN control.company_eligibility e
             ON e.identity_connection_id=c.id AND e.team_id=c.team_id
             WHERE c.team_id=team AND c.state='active' AND e.identity_id=person
                AND e.connection_revision=c.revision AND e.eligible AND e.valid_until>at_time)))
$$;
-- +goose StatementEnd

