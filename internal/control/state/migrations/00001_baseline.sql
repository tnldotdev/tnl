-- +goose StatementBegin
CREATE FUNCTION control.company_authentication_current(team text, person text, session text, at_time timestamptz)
RETURNS boolean LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM control.company_session_contexts proof
            JOIN control.control_sessions s ON s.id=proof.session_id AND s.identity_id=person
                AND s.revoked_at IS NULL AND s.refresh_expires_at>at_time
            JOIN control.identity_connections c ON c.id=proof.identity_connection_id AND c.team_id=team
                AND c.state='active' AND c.revision=proof.connection_revision
            JOIN control.company_eligibility e ON e.identity_connection_id=c.id AND e.identity_id=person
                AND e.subject=proof.subject AND e.connection_revision=c.revision AND e.eligible AND e.valid_until>at_time
            WHERE proof.session_id=session AND proof.team_id=team AND proof.authenticated_at<=at_time
                AND proof.expires_at>at_time)
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION control.company_session_authorized(team text, person text, session text, at_time timestamptz)
RETURNS boolean LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM control.team_memberships m JOIN control.teams t ON t.id=m.team_id
        WHERE m.team_id=team AND m.identity_id=person AND control.active_membership(m.id,at_time)
        AND (m.personal_account_exception OR NOT t.company_sign_in_required
            OR control.company_authentication_current(team,person,session,at_time)))
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION control.company_subject_session_authorized(team text, person text, session text, at_time timestamptz)
RETURNS boolean LANGUAGE sql STABLE AS $$
    SELECT control.active_team_subject(team,person,at_time) AND
        ((NOT EXISTS (SELECT 1 FROM control.team_memberships m WHERE m.team_id=team AND m.identity_id=person)
          AND (NOT EXISTS (SELECT 1 FROM control.company_eligibility e JOIN control.identity_connections c ON c.id=e.identity_connection_id WHERE e.team_id=team AND e.identity_id=person AND c.activated_at IS NOT NULL)
               OR control.company_authentication_current(team,person,session,at_time)))
         OR control.company_session_authorized(team,person,session,at_time))
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION control.company_subject_deadline(team text, person text, session text, at_time timestamptz)
RETURNS timestamptz LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN NOT control.company_subject_session_authorized(team,person,session,at_time) THEN at_time
    ELSE COALESCE((SELECT LEAST(e.valid_until,proof.expires_at) FROM control.teams t
        JOIN control.identity_connections c ON c.team_id=t.id AND c.state='active'
        JOIN control.company_eligibility e ON e.identity_connection_id=c.id AND e.identity_id=person
        JOIN control.company_session_contexts proof ON proof.session_id=session AND proof.team_id=t.id AND proof.identity_connection_id=c.id
        WHERE t.id=team AND t.company_sign_in_required AND NOT EXISTS (
            SELECT 1 FROM control.team_memberships m WHERE m.team_id=team AND m.identity_id=person
                AND m.removed_at IS NULL AND m.personal_account_exception)),
        'infinity'::timestamptz) END
$$;
-- +goose StatementEnd

