-- the managed domain is shared; a custom default must belong to the team.
-- the foreign key above protects existence, and this check protects ownership.
-- +goose StatementBegin
CREATE FUNCTION control.check_team_default_domain() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.default_domain_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM control.domains AS domains
        WHERE domains.id = NEW.default_domain_id
          AND (domains.kind = 'managed' OR domains.team_id = NEW.id)
    ) THEN
        RAISE EXCEPTION 'team default domain must be managed or owned by the team' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER check_team_default_domain
BEFORE INSERT OR UPDATE OF default_domain_id ON control.teams
FOR EACH ROW EXECUTE FUNCTION control.check_team_default_domain();

