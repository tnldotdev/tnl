-- +goose Up
-- existing teams and urls stay on the current ingress address. an operator must
-- configure and verify the address before new pool-aware allocation is enabled.
CREATE TABLE control.ingress_pools (
    id text PRIMARY KEY CHECK (id <> ''),
    ipv4_address inet,
    ipv6_address inet,
    state text NOT NULL CHECK (state IN ('disabled', 'enabled', 'draining')),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CHECK (ipv4_address IS NULL OR family(ipv4_address) = 4),
    CHECK (ipv6_address IS NULL OR family(ipv6_address) = 6),
    CHECK (state = 'disabled' OR ipv4_address IS NOT NULL OR ipv6_address IS NOT NULL),
    CHECK (updated_at >= created_at)
);
