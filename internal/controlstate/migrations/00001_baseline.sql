CREATE SCHEMA IF NOT EXISTS control;

-- the baseline identity prevents a different version-1 schema from being
-- mistaken for this coordinated fresh-database cutover.
CREATE TABLE control.schema_identity (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    baseline_id text NOT NULL CHECK (baseline_id = 'tnl-control-fresh-v1-protocol-rewrite')
);
INSERT INTO control.schema_identity (id, baseline_id) VALUES (1, 'tnl-control-fresh-v1-protocol-rewrite');

CREATE TABLE control.identities (
    id text PRIMARY KEY CHECK (id <> ''),
    kind text NOT NULL CHECK (kind IN ('builtin', 'oidc', 'authority')),
    issuer text,
    subject text,
    display_name text NOT NULL CHECK (display_name <> ''),
    normalized_email text,
    email_verified boolean NOT NULL DEFAULT false,
    administrator boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    disabled_at timestamptz,
    CHECK ((issuer IS NULL) = (subject IS NULL)),
    CHECK (kind = 'oidc' OR issuer IS NULL),
    CHECK (normalized_email IS NOT NULL OR NOT email_verified),
    CHECK (updated_at >= created_at),
    CHECK (disabled_at IS NULL OR disabled_at >= created_at)
);

CREATE UNIQUE INDEX identities_oidc_subject
    ON control.identities (issuer, subject)
    WHERE issuer IS NOT NULL;
CREATE UNIQUE INDEX identities_builtin_singleton
    ON control.identities (kind)
    WHERE kind = 'builtin';

-- select the ingress pool before creating a team; saved URLs pin its choice.
CREATE TABLE control.ingress_pools (
    id text PRIMARY KEY CHECK (id <> ''),
    ipv4_address inet CHECK (family(ipv4_address) = 4),
    ipv6_address inet CHECK (family(ipv6_address) = 6),
