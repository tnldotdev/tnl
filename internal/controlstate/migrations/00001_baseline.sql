CREATE FUNCTION control.normalize_team_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF char_length(NEW.display_name) NOT BETWEEN 1 AND 63 OR NEW.display_name !~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?$' THEN
        NEW.display_name := NEW.managed_label;
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd
CREATE TRIGGER normalize_team_name BEFORE INSERT ON control.teams FOR EACH ROW EXECUTE FUNCTION control.normalize_team_name();
