import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";

import { build } from "esbuild";

const root = path.resolve(import.meta.dirname, "..");
const sourcePath = path.join(root, "internal", "feedbacktoolbar", "toolbar.tsx");
const outputPath = path.join(root, "internal", "feedbacktoolbar", "toolbar.js");
const result = await build({
  entryPoints: [sourcePath],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  jsx: "transform",
  jsxFactory: "h",
  minify: true,
  legalComments: "none",
});
const output = result.outputFiles?.at(0);
if (result.outputFiles?.length !== 1 || !output)
  throw new Error("expected one bundled feedback toolbar");
const bundled = `// Code generated by scripts/build-feedback-toolbar.ts. DO NOT EDIT.\n${output.text}`;
new vm.Script(bundled, { filename: "toolbar.js" });
const digest = createHash("sha256").update(bundled).digest("hex");
await writeFile(outputPath, bundled);
process.stdout.write(`built feedback toolbar ${digest.slice(0, 12)}\n`);
