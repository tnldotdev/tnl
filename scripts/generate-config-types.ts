import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { compile } from "json-schema-to-typescript";
import * as z from "zod";
import { parseJSON, parseValue } from "./validation.ts";

const root = path.resolve(import.meta.dirname, "..");
const schemaObject = z.record(z.string(), z.unknown());
const schema = parseJSON(
  await readFile(path.join(root, "schema", "v1.json"), "utf8"),
  z.object({
    $schema: z.string(),
    $defs: z.object({ TNL: schemaObject, Publish: schemaObject, Readiness: schemaObject }),
  }),
  "configuration schema",
);
const keys = parseJSON(
  await readFile(path.join(root, "internal", "projectconfig", "keys.gen.json"), "utf8"),
  z.record(z.string(), z.string()),
  "configuration key mappings",
);
const client = {
  ...schema.$defs.TNL,
  $schema: schema.$schema,
  $defs: { Publish: schema.$defs.Publish, Readiness: schema.$defs.Readiness },
};
renameProperties(client, keys);

const generated = await compile(client, "TnlConfig", {
  bannerComment: "",
  format: false,
  strictIndexSignatures: true,
  style: { singleQuote: false },
});
const ratePeriods = generated.match(/\bper: string\b/g);
if (ratePeriods?.length !== 2) {
  throw new Error("expected rate.per in project and service configuration declarations");
}
const typedConfig = generated.replaceAll("per: string", "per: TnlRatePeriod");
const declarations = `// Code generated by scripts/generate-config-types.ts. DO NOT EDIT.

import type { TnlProjectMetadata } from "./index.js";

type TnlRateSegment = \`\${number}\${"ns" | "us" | "µs" | "ms" | "s" | "m" | "h"}\`;

/** a Go duration with one to four numeric unit segments; tnl checks positivity at runtime. */
export type TnlRatePeriod =
  | TnlRateSegment
  | \`\${TnlRateSegment}\${TnlRateSegment}\`
  | \`\${TnlRateSegment}\${TnlRateSegment}\${TnlRateSegment}\`
  | \`\${TnlRateSegment}\${TnlRateSegment}\${TnlRateSegment}\${TnlRateSegment}\`;

${typedConfig.trim()}

/** The Git worktree or project directory that contains tnl.config.ts. */
export interface TnlWorktree {
  readonly isGit: boolean;
  /** DNS-safe project/worktree label derived from this checkout and client state. */
  readonly label: RegisteredWorktreeLabel;
  readonly name: string;
  readonly root: string;
}

export interface TnlWorktreeLabel {
  readonly project: string;
  readonly checkout?: string;
  readonly id: string;
  readonly fullLabel: string;
}

type RegisteredWorktreeLabel = TnlProjectMetadata extends {
  readonly worktree: { readonly label: infer Label extends TnlWorktreeLabel };
} ? Label : TnlWorktreeLabel;

/** Values passed to a tnl.config.ts configuration factory. */
export interface TnlConfigContext {
  readonly cwd: string;
  readonly env: Readonly<Record<string, string | undefined>>;
  readonly worktree: TnlWorktree;
  readonly project: { readonly relativeDirectory: string };
}

export type TnlConfigFactory = (
  context: TnlConfigContext,
) => TnlConfig | Promise<TnlConfig>;

export type TnlConfigInput = TnlConfig | TnlConfigFactory;
`;
await writeFile(path.join(root, "packages", "ts", "src", "config.gen.ts"), declarations);

function renameProperties(value: unknown, mappings: Readonly<Record<string, string>>): void {
  if (Array.isArray(value)) {
    for (const item of value) {
      renameProperties(item, mappings);
    }
    return;
  }
  if (value === null || typeof value !== "object") {
    return;
  }
  const object = parseValue(value, schemaObject, "schema node");
  if (object.properties !== undefined) {
    const properties = parseValue(object.properties, schemaObject, "schema properties");
    for (const [staticName, typeScriptName] of Object.entries(mappings)) {
      if (Object.hasOwn(properties, staticName)) {
        properties[typeScriptName] = properties[staticName];
        delete properties[staticName];
      }
    }
    object.properties = properties;
  }
  if (object.required !== undefined) {
    const required = parseValue(object.required, z.array(z.string()), "required schema fields");
    object.required = required.map((name) => mappings[name] ?? name);
  }
  // zod parses a copy; apply the validated changes to the schema being walked.
  Object.assign(value, object);
  for (const child of Object.values(value)) {
    renameProperties(child, mappings);
  }
}
