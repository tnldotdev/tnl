import { execFileSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, readdir, rm, unlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseDocument, stringify } from "yaml";

const generatedHeader = "// Code generated by sqlc. DO NOT EDIT.";

function record(value: unknown): Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error("sqlc configuration must contain an object");
  }
  return value as Record<string, unknown>;
}

function inputPaths(value: unknown, directory: string, staged: string): string | string[] {
  if (typeof value === "string") return relative(staged, resolve(directory, value));
  if (Array.isArray(value) && value.every((path): path is string => typeof path === "string")) {
    return value.map((path) => relative(staged, resolve(directory, path)));
  }
  throw new Error("sqlc schema and query paths must be strings");
}

// stage the complete output before touching committed files. sqlc itself does
// not remove output for deleted queries; only its marked files belong to us.
export async function generateSQL(configPath: string): Promise<void> {
  configPath = resolve(configPath);
  const configuration = record(parseDocument(await readFile(configPath, "utf8")).toJS());
  if (!Array.isArray(configuration.sql) || configuration.sql.length === 0) {
    throw new Error("sqlc configuration needs SQL sources");
  }
  const temporary = await mkdtemp(join(tmpdir(), "tnl-sqlc-"));
  try {
    const outputs: { staged: string; destination: string }[] = [];
    for (const [index, value] of configuration.sql.entries()) {
      const source = record(value);
      const go = record(record(source.gen).go);
      if (typeof go.out !== "string" || go.out === "") {
        throw new Error("sqlc Go output directory is missing");
      }
      const staged = join(temporary, `output-${index}`);
      outputs.push({ staged, destination: resolve(dirname(configPath), go.out) });
      // sqlc joins these paths to its config directory, including absolute paths.
      go.out = relative(temporary, staged);
      source.schema = inputPaths(source.schema, dirname(configPath), temporary);
      source.queries = inputPaths(source.queries, dirname(configPath), temporary);
    }
    const stagedConfig = join(temporary, "sqlc.yaml");
    await writeFile(stagedConfig, stringify(configuration));
    execFileSync("sqlc", ["generate", "-f", stagedConfig], { stdio: "inherit" });
    for (const output of outputs) {
      const generated = new Map<string, string>();
      for (const entry of await readdir(output.staged, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".go")) {
          throw new Error(`unexpected sqlc output: ${entry.name}`);
        }
        const content = await readFile(join(output.staged, entry.name), "utf8");
        if (!content.startsWith(generatedHeader)) {
          throw new Error(`sqlc output lacks its generated marker: ${entry.name}`);
        }
        generated.set(entry.name, content);
      }
      await mkdir(output.destination, { recursive: true });
      const obsolete: string[] = [];
      for (const entry of await readdir(output.destination, { withFileTypes: true })) {
        if (generated.has(entry.name) && !entry.isFile()) {
          throw new Error(
            `refusing to overwrite non-file output: ${join(output.destination, entry.name)}`,
          );
        }
        if (!entry.isFile() || !entry.name.endsWith(".go")) continue;
        const path = join(output.destination, entry.name);
        const content = await readFile(path, "utf8");
        if (content.startsWith(generatedHeader)) {
          if (!generated.has(entry.name)) obsolete.push(path);
        } else if (generated.has(entry.name)) {
          throw new Error(`refusing to overwrite handwritten file: ${path}`);
        }
      }
      for (const [name, content] of generated) {
        await writeFile(join(output.destination, name), content);
      }
      for (const path of obsolete) await unlink(path);
    }
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const root = resolve(import.meta.dirname, "../..");
  for (const owner of ["client", "control"]) {
    await generateSQL(join(root, "internal", owner, "state", "sqlc.yaml"));
  }
}
