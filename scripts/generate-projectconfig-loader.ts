import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";

const root = path.resolve(import.meta.dirname, "..");
const outputPath = path.join(root, "internal", "projectconfig", "loader.mjs");
const run = promisify(execFile);
const directory = await mkdtemp(path.join(tmpdir(), "tnl-loader-"));
try {
  await run(
    "pnpm",
    ["exec", "tsc", "--project", "internal/projectconfig/tsconfig.json", "--outDir", directory],
    { cwd: root },
  );
  const compiled = await readFile(path.join(directory, "loader.js"), "utf8");
  await writeFile(
    outputPath,
    `// Code generated by scripts/generate-projectconfig-loader.ts. DO NOT EDIT.\n\n${compiled}`,
  );
  await run("pnpm", ["exec", "oxfmt", "--write", outputPath], { cwd: root });
} finally {
  await rm(directory, { force: true, recursive: true });
}
import { installToolFailureHandler } from "./errors.ts";
installToolFailureHandler(import.meta);
